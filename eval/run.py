"""Eval suite entry point.

    uv run python -m eval.run --suite quick
    uv run python -m eval.run --suite trap
    uv run python -m eval.run --suite full

Exit codes:
    0  all (non-skipped) cases passed
    1  at least one case failed (e.g. a trap was not caught -> 100% recall gate)
"""

from __future__ import annotations

import argparse
import pathlib
import sys

from eval._harness import RUN_DATE, SuiteReport, boot_registry, print_table

DOCS_EVAL = pathlib.Path(__file__).parent.parent / "docs" / "EVAL.md"


def _run(suite: str) -> tuple[list[SuiteReport], bool]:
    """Run the named suite. Returns (reports, ok)."""
    boot_registry()

    if suite == "trap":
        from eval.traps import run_trap_suite

        report = run_trap_suite()
        print_table(report)
        # 100% recall gate: every trap must be caught.
        ok = report.all_passed and report.n_pass == len(report.cases)
        if not ok:
            print("\nTRAP GATE FAILED: not all traps were caught (100% recall required).")
        else:
            print(f"\nTRAP GATE: 100% recall ({report.n_pass}/{len(report.cases)} caught).")
        return [report], ok

    if suite == "quick":
        from eval.quick import run_quick_suite

        report = run_quick_suite()
        print_table(report)
        return [report], report.all_passed

    if suite == "full":
        from eval.full import run_full_suite

        stub, quick, trap = run_full_suite()
        print()
        print_table(stub)
        print()
        print_table(quick)
        print()
        print_table(trap)
        trap_ok = trap.all_passed and trap.n_pass == len(trap.cases)
        ok = stub.all_passed and quick.all_passed and trap_ok
        return [stub, quick, trap], ok

    raise ValueError(f"unknown suite: {suite}")


def _write_eval_md(suite: str, reports: list[SuiteReport]) -> None:
    """Write/refresh docs/EVAL.md with a results table for this run."""
    lines: list[str] = []
    lines.append("# Lattice Eval Results")
    lines.append("")
    lines.append(
        "> Generated by `uv run python -m eval.run --suite <suite>`. "
        "Re-run to refresh. Date is the static project run date "
        "(reproducible; not wall-clock)."
    )
    lines.append("")
    lines.append("## Targets (AGENTS.md — do not loosen without an ADR)")
    lines.append("")
    lines.append("| Metric | Target | Status |")
    lines.append("|---|---|---|")
    lines.append(
        "| Cell-type annotation F1 vs published | >= 0.75 | not built (annotate primitives pending) |"
    )
    lines.append(
        "| DE top-50 overlap with published | >= 60% | not built (de primitives pending) |"
    )
    lines.append("| Trap detection recall | 100% | enforced by `--suite trap` |")
    lines.append("| Reproducibility (bit-identical) | 100% | covered by primitive tests |")
    lines.append("| Standalone notebook validity | 100% | not built (export pending, M4) |")
    lines.append("")
    lines.append(f"## Last run — suite `{suite}` ({RUN_DATE})")
    lines.append("")
    lines.append("| Suite | Dataset | Metric | Value | Result | Date |")
    lines.append("|---|---|---|---|---|---|")
    for report in reports:
        for c in report.cases:
            result = "SKIP" if c.skipped else ("PASS" if c.passed else "FAIL")
            lines.append(
                f"| {c.suite} | {c.dataset} | {c.metric} | {c.value} | {result} | {RUN_DATE} |"
            )
    lines.append("")
    lines.append("### Notes")
    lines.append("")
    lines.append(
        "- **Trap suite** is the 100%-recall PR gate: each synthetic dataset injects a "
        "known failure mode and the matching primitive sanity check must fire."
    )
    lines.append(
        "- **Quick suite** runs the standard scRNA-seq chain on PBMC 3k. The "
        "`cluster-agreement ARI` value is a PLACEHOLDER for the annotation-F1 target — "
        "annotation primitives are not built yet, so ARI vs published cluster labels "
        "stands in as a sanity signal and is not gated."
    )
    lines.append(
        "- **Full suite** currently runs quick + trap and lists the published datasets "
        "(5 treatment-vs-control studies + HCA immune) that remain to be wired."
    )
    lines.append("")

    DOCS_EVAL.parent.mkdir(parents=True, exist_ok=True)
    DOCS_EVAL.write_text("\n".join(lines), encoding="utf-8")
    print(f"\nWrote results to {DOCS_EVAL}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m eval.run",
        description="Run the Lattice eval suites.",
    )
    parser.add_argument(
        "--suite",
        choices=["quick", "full", "trap"],
        default="quick",
        help="Which suite to run (default: quick).",
    )
    parser.add_argument(
        "--no-write",
        action="store_true",
        help="Do not update docs/EVAL.md.",
    )
    args = parser.parse_args(argv)

    reports, ok = _run(args.suite)

    if not args.no_write:
        _write_eval_md(args.suite, reports)

    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
